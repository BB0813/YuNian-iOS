/* ── AES-256-CBC utility (delegates to whitebox-aes.h) ── */

/**
 * Decrypt one string from the table.
 * @param id    String ID (0..SS_COUNT-1)
 * @param out   Output: pointer to heap-allocated plaintext (caller must free)
 * @param out_len Output: length of plaintext (excluding null terminator)
 * @return 0 on success, -1 on invalid ID or decrypt failure
 */
extern "C"
int secure_string_get(int id, char** out, size_t* out_len) {
    OBF_BARRIER(132);
    if (id < 0 || id >= SS_COUNT || !out || !out_len) return -1;

    const uint8_t* entry = kEncryptedStrings[id];
    uint8_t iv[AES_BLOCK_SIZE];
    uint8_t key[AES_KEY_SIZE];

    /* Unmask the embedded key */
    for (int i = 0; i < AES_KEY_SIZE; i++) {
        key[i] = kKeyObf[i] ^ kKeyMask[i];
    }

    /* Extract IV (first 16 bytes of entry) */
    memcpy(iv, entry, AES_BLOCK_SIZE);

    /* Ciphertext starts after IV; determine length from the table metadata */
    /* Each entry is a fixed 256-byte slot: IV[16] + ciphertext[240] */
    const uint8_t* ciphertext = entry + AES_BLOCK_SIZE;
    size_t ciphertext_len = 240; /* max slot size minus IV */

    /* Allocate output buffer (padded size, will trim PKCS7 after decrypt) */
    uint8_t* plaintext = (uint8_t*)calloc(1, ciphertext_len + 1);
    if (!plaintext) return -1;

    /* Delegate to whitebox AES-256-CBC decrypt */
    int res = wb_aes_256_cbc_decrypt(ciphertext, plaintext, ciphertext_len, iv);
    if (res != 0) {
        memset(plaintext, 0, ciphertext_len + 1);
        free(plaintext);
        memset(key, 0, sizeof(key));
        memset(iv, 0, sizeof(iv));
        return -1;
    }

    /* Strip PKCS7 padding */
    uint8_t pad = plaintext[ciphertext_len - 1];
    if (pad == 0 || pad > AES_BLOCK_SIZE) {
        memset(plaintext, 0, ciphertext_len + 1);
        free(plaintext);
        memset(key, 0, sizeof(key));
        memset(iv, 0, sizeof(iv));
        return -1;
    }
    size_t actual_len = ciphertext_len - pad;
    plaintext[actual_len] = '\0';

    *out = (char*)plaintext;
    *out_len = actual_len;

    /* Zero sensitive key material */
    memset(key, 0, sizeof(key));
    memset(iv, 0, sizeof(iv));

    return 0;
}

/**
 * Zero and free a string previously returned by secure_string_get().
 */
extern "C"
void secure_string_free(char* str, size_t len) {
    OBF_BARRIER(192);
    if (str) {
        if (len > 0) memset(str, 0, len + 1);
        free(str);
    }
}
